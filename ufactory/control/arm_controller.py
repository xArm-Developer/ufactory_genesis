"""Unified hardware-parity virtual ArmMotionController (pure NumPy).

Supports all 5 UFACTORY arms (xArm5 / xArm6 / xArm7 / UF850 / Lite6), per-unit
kinematics calibration, TCP offset, Mode 0 (default 250 Hz MoveJ/MoveL planning
via ``set_servo_angle`` / ``set_position``), Mode 1 (default 50 Hz, 30-250 Hz
configurable servo streaming via ``set_servo_angle_j`` / ``set_servo_cartesian``),
and xArm-SDK-compatible ``set_allow_approx_motion`` singularity avoidance.
"""

from __future__ import annotations

from collections.abc import Iterator, Sequence
from contextlib import contextmanager
from dataclasses import dataclass
import math
from pathlib import Path
from typing import Any

import numpy as np

from ufactory.config.assets import RepositoryAssetStore
from ufactory.control.kinematics_chain import (
    CalibratedKinematicsChain,
    pose_to_se3,
    slerp_rotation,
    so3_log,
)
from ufactory.control.solvers import (
    ApproxMotionConfig,
    IKStepResult,
    solve_cartesian_step,
    solve_exact_ik,
)
from ufactory.trajectory.profile import (
    _EPS,
    _lspb_alpha_for_duration,
    _lspb_displacement,
    _sample_grid,
    joint_lspb_samples,
    lspb_duration,
)
from ufactory.types import FloatArray

MODE_POSITION = 0
MODE_SERVO = 1

STATE_READY = 0
STATE_PAUSE = 3
STATE_STOP = 4

# Controller error codes matching xArm firmware conventions
ERROR_NONE = 0
ERROR_IK_FAILED = 21
ERROR_OVERSPEED = 24
ERROR_INVALID_MODE = -1
ERROR_INVALID_ARG = -2

DEFAULT_CONTROL_RATE_HZ = 250.0  # Firmware Mode 0 internal interpolation rate (4 ms)
DEFAULT_SERVO_RATE_HZ = 50.0  # Default Mode 1 streaming rate (20 ms)
MIN_SERVO_RATE_HZ = 30.0
MAX_SERVO_RATE_HZ = 250.0

# Official UFACTORY hardware joint velocity cap (~180 deg/s)
DEFAULT_HARDWARE_JOINT_SPEED_LIMIT_RAD_S = math.pi
DEFAULT_MOVEJ_SPEED_RAD_S = 1.0
DEFAULT_MOVEJ_ACC_RAD_S2 = 10.0
DEFAULT_MOVEL_SPEED_MM_S = 150.0
DEFAULT_MOVEL_ACC_MM_S2 = 800.0
DEFAULT_ROT_SPEED_RAD_S = 1.0
DEFAULT_ROT_ACC_RAD_S2 = 5.0


@dataclass(frozen=True)
class PlannedMotion:
    """Deterministic trajectory generated by Mode 0 ``set_servo_angle`` / ``set_position``."""

    kind: str  # "movej" | "movel"
    rate_hz: float
    duration_s: float
    q_samples: FloatArray  # (N, dof) rad
    timestamps_s: FloatArray  # (N,) s
    error_code: int = ERROR_NONE
    used_approx_steps: int = 0
    max_position_error_m: float = 0.0
    max_orientation_error_rad: float = 0.0
    max_joint_speed_rad_s: float = 0.0
    message: str = ""


class ArmMotionController:
    """Pure-NumPy motion controller mirroring UFACTORY firmware behavior across all 5 arms."""

    def __init__(
        self,
        chain: CalibratedKinematicsChain,
        *,
        control_rate_hz: float = DEFAULT_CONTROL_RATE_HZ,
        servo_rate_hz: float = DEFAULT_SERVO_RATE_HZ,
        allow_approx_motion: bool = False,
        approx_config: ApproxMotionConfig | None = None,
        joint_speed_limit_rad_s: float = DEFAULT_HARDWARE_JOINT_SPEED_LIMIT_RAD_S,
        initial_q_rad: Sequence[float] | FloatArray | None = None,
        hardware_arm: Any | None = None,
    ) -> None:
        if not math.isfinite(control_rate_hz) or control_rate_hz <= 0.0:
            raise ValueError("control_rate_hz must be finite and positive")
        if not math.isfinite(servo_rate_hz) or not (MIN_SERVO_RATE_HZ <= servo_rate_hz <= MAX_SERVO_RATE_HZ):
            raise ValueError(f"servo_rate_hz must lie in [{MIN_SERVO_RATE_HZ}, {MAX_SERVO_RATE_HZ}] Hz")
        if not isinstance(allow_approx_motion, bool):
            raise TypeError("allow_approx_motion must be a bool")
        if not math.isfinite(joint_speed_limit_rad_s) or joint_speed_limit_rad_s <= 0.0:
            raise ValueError("joint_speed_limit_rad_s must be finite and positive")

        self._chain = chain
        self._control_rate_hz = float(control_rate_hz)
        self._servo_rate_hz = float(servo_rate_hz)
        self._allow_approx_motion = bool(allow_approx_motion)
        self._approx_config = approx_config or ApproxMotionConfig()
        self._joint_speed_limit_rad_s = float(joint_speed_limit_rad_s)
        self._hardware_arm = hardware_arm

        self._mode: int = MODE_POSITION
        self._state: int = STATE_READY
        self._error_code: int = ERROR_NONE
        self._q_rad: FloatArray = (
            np.zeros(chain.dof, dtype=np.float64) if initial_q_rad is None else chain.validate_q(initial_q_rad).copy()
        )
        self._last_motion: PlannedMotion | None = None
        self._last_step: IKStepResult | None = None

    @classmethod
    def from_robot(
        cls,
        robot_key: str,
        *,
        urdf_path: str | Path | None = None,
        calibration_path: str | Path | None = None,
        serial_number: str | None = None,
        tcp_offset_mm_rpy: Sequence[float] | FloatArray | None = None,
        control_rate_hz: float = DEFAULT_CONTROL_RATE_HZ,
        servo_rate_hz: float = DEFAULT_SERVO_RATE_HZ,
        allow_approx_motion: bool = False,
        approx_config: ApproxMotionConfig | None = None,
        joint_speed_limit_rad_s: float = DEFAULT_HARDWARE_JOINT_SPEED_LIMIT_RAD_S,
        initial_q_rad: Sequence[float] | FloatArray | None = None,
        hardware_arm: Any | None = None,
        asset_store: RepositoryAssetStore | None = None,
    ) -> ArmMotionController:
        """Instantiate a controller for any of the 5 UFACTORY arms with optional calibration."""

        chain = CalibratedKinematicsChain.from_robot(
            robot_key,
            urdf_path=urdf_path,
            calibration_path=calibration_path,
            serial_number=serial_number,
            tcp_offset_mm_rpy=tcp_offset_mm_rpy,
            asset_store=asset_store,
        )
        return cls(
            chain,
            control_rate_hz=control_rate_hz,
            servo_rate_hz=servo_rate_hz,
            allow_approx_motion=allow_approx_motion,
            approx_config=approx_config,
            joint_speed_limit_rad_s=joint_speed_limit_rad_s,
            initial_q_rad=initial_q_rad,
            hardware_arm=hardware_arm,
        )

    # ------------------------------------------------------------------ properties

    @property
    def chain(self) -> CalibratedKinematicsChain:
        return self._chain

    @property
    def robot_key(self) -> str:
        return self._chain.robot_key

    @property
    def dof(self) -> int:
        return self._chain.dof

    @property
    def control_rate_hz(self) -> float:
        return self._control_rate_hz

    @property
    def servo_rate_hz(self) -> float:
        return self._servo_rate_hz

    @property
    def mode(self) -> int:
        return self._mode

    @property
    def state(self) -> int:
        return self._state

    @property
    def error_code(self) -> int:
        return self._error_code

    @property
    def is_approx_motion(self) -> bool:
        """Mirror ``XArmAPI.is_approx_motion``."""

        return self._allow_approx_motion

    @property
    def tcp_offset(self) -> FloatArray:
        return self._chain.tcp_offset_mm_rpy.copy()

    @property
    def last_motion(self) -> PlannedMotion | None:
        return self._last_motion

    @property
    def last_step(self) -> IKStepResult | None:
        return self._last_step

    @property
    def approx_config(self) -> ApproxMotionConfig:
        return self._approx_config

    # ------------------------------------------------------------------ xArm-SDK-compatible configuration & state

    def set_mode(self, mode: int) -> int:
        if isinstance(mode, bool) or int(mode) not in (MODE_POSITION, MODE_SERVO):
            return ERROR_INVALID_MODE
        self._mode = int(mode)
        if self._hardware_arm is not None:
            return int(self._hardware_arm.set_mode(self._mode))
        return ERROR_NONE

    def set_state(self, state: int) -> int:
        if isinstance(state, bool) or int(state) not in (STATE_READY, STATE_PAUSE, STATE_STOP):
            return ERROR_INVALID_ARG
        self._state = int(state)
        if self._hardware_arm is not None:
            return int(self._hardware_arm.set_state(self._state))
        return ERROR_NONE

    def clean_error(self) -> int:
        self._error_code = ERROR_NONE
        if self._state == STATE_STOP:
            self._state = STATE_READY
        if self._hardware_arm is not None:
            return int(self._hardware_arm.clean_error())
        return ERROR_NONE

    def set_allow_approx_motion(self, on_off: bool) -> int:
        """Enable/disable singularity approximate DLS motion (mirrors ``XArmAPI.set_allow_approx_motion``)."""

        if not isinstance(on_off, bool):
            raise TypeError("on_off must be a bool")
        self._allow_approx_motion = bool(on_off)
        if self._hardware_arm is not None:
            return int(self._hardware_arm.set_allow_approx_motion(self._allow_approx_motion))
        return ERROR_NONE

    def get_allow_approx_motion(self) -> tuple[int, int]:
        """Return ``(0, 1 if enabled else 0)`` matching ``XArmAPI.get_allow_approx_motion``."""

        return (ERROR_NONE, 1 if self._allow_approx_motion else 0)

    def set_tcp_offset(self, offset: Sequence[float] | FloatArray, *, is_radian: bool = True) -> int:
        """Set tool-center-point offset ``[x_mm, y_mm, z_mm, roll, pitch, yaw]``."""

        arr = np.asarray(offset, dtype=np.float64).reshape(-1)
        if arr.shape != (6,) or not np.all(np.isfinite(arr)):
            return ERROR_INVALID_ARG
        offset_rad = arr.copy()
        if not is_radian:
            offset_rad[3:] = np.deg2rad(offset_rad[3:])
        self._chain = self._chain.with_tcp_offset(offset_rad)
        if self._hardware_arm is not None:
            return int(self._hardware_arm.set_tcp_offset(offset_rad.tolist(), is_radian=True))
        return ERROR_NONE

    def set_control_rate(self, rate_hz: float) -> None:
        if not math.isfinite(rate_hz) or rate_hz <= 0.0:
            raise ValueError("control_rate_hz must be finite and positive")
        self._control_rate_hz = float(rate_hz)

    def set_servo_rate(self, rate_hz: float) -> None:
        if not math.isfinite(rate_hz) or not (MIN_SERVO_RATE_HZ <= rate_hz <= MAX_SERVO_RATE_HZ):
            raise ValueError(f"servo_rate_hz must lie in [{MIN_SERVO_RATE_HZ}, {MAX_SERVO_RATE_HZ}] Hz")
        self._servo_rate_hz = float(rate_hz)

    def reset_state(self, q_rad: Sequence[float] | FloatArray) -> None:
        """Set virtual joint state without moving hardware."""

        self._q_rad = self._chain.validate_q(q_rad).copy()
        self._error_code = ERROR_NONE
        self._state = STATE_READY

    def get_servo_angle(self, *, is_radian: bool = True) -> tuple[int, list[float]]:
        """Return ``(0, angles)`` matching ``XArmAPI.get_servo_angle``."""

        angles = self._q_rad if is_radian else np.rad2deg(self._q_rad)
        return (ERROR_NONE, [float(v) for v in angles])

    def get_position(self, *, is_radian: bool = True) -> tuple[int, list[float]]:
        """Return ``(0, [x_mm, y_mm, z_mm, roll, pitch, yaw])`` matching ``XArmAPI.get_position``."""

        pose = self._chain.forward_pose_mm_rpy(self._q_rad, include_tcp=True)
        if not is_radian:
            pose[3:] = np.rad2deg(pose[3:])
        return (ERROR_NONE, [float(v) for v in pose])

    # ------------------------------------------------------------------ FK / IK queries (SDK-compatible)

    def get_forward_kinematics(
        self,
        angles: Sequence[float] | FloatArray,
        *,
        input_is_radian: bool = True,
        return_is_radian: bool = True,
    ) -> tuple[int, list[float]]:
        """Compute TCP pose ``[x_mm, y_mm, z_mm, roll, pitch, yaw]`` from joint angles."""

        try:
            q = np.asarray(angles, dtype=np.float64).reshape(-1)[: self.dof]
            if not input_is_radian:
                q = np.deg2rad(q)
            pose = self._chain.forward_pose_mm_rpy(q, include_tcp=True)
            if not return_is_radian:
                pose[3:] = np.rad2deg(pose[3:])
            return (ERROR_NONE, [float(v) for v in pose])
        except ValueError:
            return (ERROR_INVALID_ARG, [])

    def get_inverse_kinematics(
        self,
        pose: Sequence[float] | FloatArray,
        *,
        input_is_radian: bool = True,
        return_is_radian: bool = True,
        seed_q: Sequence[float] | FloatArray | None = None,
    ) -> tuple[int, list[float]]:
        """Solve exact IK for TCP pose ``[x_mm, y_mm, z_mm, roll, pitch, yaw]``."""

        try:
            pose_arr = np.asarray(pose, dtype=np.float64).reshape(-1)
            if pose_arr.shape != (6,) or not np.all(np.isfinite(pose_arr)):
                return (ERROR_INVALID_ARG, [])
            pose_rad = pose_arr.copy()
            if not input_is_radian:
                pose_rad[3:] = np.deg2rad(pose_rad[3:])
            target_se3 = pose_to_se3(pose_rad, position_in_mm=True)
            seed = self._q_rad if seed_q is None else self._chain.validate_q(seed_q)
            res = solve_exact_ik(
                self._chain,
                target_se3,
                seed,
                include_tcp=True,
                cold_start_fallback=True,
            )
            out = res.q_rad if return_is_radian else np.rad2deg(res.q_rad)
            return (ERROR_NONE, [float(v) for v in out])
        except ValueError:
            return (ERROR_IK_FAILED, [])

    # ------------------------------------------------------------------ Mode 0 planning & execution (default 250 Hz)

    def plan_move_j(
        self,
        target_q_rad: Sequence[float] | FloatArray,
        *,
        start_q_rad: Sequence[float] | FloatArray | None = None,
        speed_rad_s: float = DEFAULT_MOVEJ_SPEED_RAD_S,
        acc_rad_s2: float = DEFAULT_MOVEJ_ACC_RAD_S2,
        rate_hz: float | None = None,
    ) -> PlannedMotion:
        """Plan a 250 Hz (default) synchronized LSPB MoveJ trajectory."""

        q0 = self._q_rad.copy() if start_q_rad is None else self._chain.validate_q(start_q_rad)
        q1 = self._chain.validate_q(target_q_rad)
        if np.any(q1 < self._chain.lower - 1e-7) or np.any(q1 > self._chain.upper + 1e-7):
            return PlannedMotion(
                kind="movej",
                rate_hz=float(self._control_rate_hz if rate_hz is None else rate_hz),
                duration_s=0.0,
                q_samples=q0.reshape(1, -1),
                timestamps_s=np.zeros(1, dtype=np.float64),
                error_code=ERROR_INVALID_ARG,
                message="MoveJ target exceeds joint limits",
            )
        rate = self._control_rate_hz if rate_hz is None else float(rate_hz)
        samples, n, dur = joint_lspb_samples(q0, q1, rate=rate, v_max=float(speed_rad_s), a_max=float(acc_rad_s2))
        ts = np.arange(1, n + 1, dtype=np.float64) / rate
        full = np.vstack((q0[None, :], samples))
        max_vj = float(np.max(np.abs(np.diff(full, axis=0)) * rate, initial=0.0))
        return PlannedMotion(
            kind="movej",
            rate_hz=rate,
            duration_s=dur,
            q_samples=samples,
            timestamps_s=ts,
            error_code=ERROR_NONE,
            max_joint_speed_rad_s=max_vj,
        )

    def set_servo_angle(
        self,
        angle: Sequence[float] | FloatArray,
        *,
        speed: float | None = None,
        mvacc: float | None = None,
        is_radian: bool = True,
        wait: bool = False,
    ) -> int:
        """Mode 0 joint move (mirrors ``XArmAPI.set_servo_angle``) using ``control_rate_hz`` (250 Hz default)."""

        if self._mode != MODE_POSITION or self._state != STATE_READY or self._error_code != ERROR_NONE:
            return ERROR_INVALID_MODE
        raw = np.asarray(angle, dtype=np.float64).reshape(-1)
        if raw.shape != (self.dof,) or not np.all(np.isfinite(raw)):
            return ERROR_INVALID_ARG
        target_rad = raw if is_radian else np.deg2rad(raw)
        spd = (
            DEFAULT_MOVEJ_SPEED_RAD_S if speed is None else (float(speed) if is_radian else math.radians(float(speed)))
        )
        acc = DEFAULT_MOVEJ_ACC_RAD_S2 if mvacc is None else (float(mvacc) if is_radian else math.radians(float(mvacc)))
        motion = self.plan_move_j(target_rad, speed_rad_s=spd, acc_rad_s2=acc)
        self._last_motion = motion
        if motion.error_code != ERROR_NONE:
            self._error_code = motion.error_code
            self._state = STATE_STOP
            return motion.error_code
        if self._hardware_arm is not None:
            code = int(
                self._hardware_arm.set_servo_angle(
                    angle=target_rad.tolist(),
                    speed=spd,
                    mvacc=acc,
                    is_radian=True,
                    wait=wait,
                )
            )
            if code != 0:
                return code
        self._q_rad = motion.q_samples[-1].copy()
        return ERROR_NONE

    def plan_move_l(
        self,
        target_pose_se3: FloatArray,
        *,
        start_q_rad: Sequence[float] | FloatArray | None = None,
        speed_m_s: float = DEFAULT_MOVEL_SPEED_MM_S * 1e-3,
        acc_m_s2: float = DEFAULT_MOVEL_ACC_MM_S2 * 1e-3,
        rot_speed_rad_s: float = DEFAULT_ROT_SPEED_RAD_S,
        rot_acc_rad_s2: float = DEFAULT_ROT_ACC_RAD_S2,
        rate_hz: float | None = None,
        motion_type: int = 0,
        include_tcp: bool = True,
    ) -> PlannedMotion:
        """Plan a 250 Hz (default) Cartesian MoveL trajectory (LSPB xyz + SLERP rot + IK/DLS)."""

        q0 = self._q_rad.copy() if start_q_rad is None else self._chain.validate_q(start_q_rad)
        rate = self._control_rate_hz if rate_hz is None else float(rate_hz)
        dt = 1.0 / rate
        target = np.asarray(target_pose_se3, dtype=np.float64).reshape(4, 4)

        if motion_type == 2:
            # Direct transfer to IK using joint planning
            try:
                ik_end = solve_exact_ik(self._chain, target, q0, include_tcp=include_tcp, cold_start_fallback=True)
            except ValueError as exc:
                return PlannedMotion(
                    kind="movej",
                    rate_hz=rate,
                    duration_s=0.0,
                    q_samples=q0.reshape(1, -1),
                    timestamps_s=np.zeros(1, dtype=np.float64),
                    error_code=ERROR_IK_FAILED,
                    message=str(exc),
                )
            return self.plan_move_j(ik_end.q_rad, start_q_rad=q0, rate_hz=rate)

        start_se3 = self._chain.forward_matrix(q0, include_tcp=include_tcp)
        p0 = start_se3[:3, 3]
        p1 = target[:3, 3]
        r0 = start_se3[:3, :3]
        r1 = target[:3, :3]

        lin_dist = float(np.linalg.norm(p1 - p0))
        rot_dist = float(np.linalg.norm(so3_log(r0.T @ r1)))
        if lin_dist < _EPS and rot_dist < _EPS:
            return PlannedMotion(
                kind="movel",
                rate_hz=rate,
                duration_s=0.0,
                q_samples=q0.reshape(1, -1),
                timestamps_s=np.zeros(1, dtype=np.float64),
                error_code=ERROR_NONE,
            )

        dur_lin = lspb_duration(lin_dist, speed_m_s, acc_m_s2) if lin_dist >= _EPS else 0.0
        dur_rot = lspb_duration(rot_dist, rot_speed_rad_s, rot_acc_rad_s2) if rot_dist >= _EPS else 0.0
        duration = max(dur_lin, dur_rot)
        if duration <= _EPS:
            duration = max(_EPS, lin_dist / max(speed_m_s, _EPS), rot_dist / max(rot_speed_rad_s, _EPS))
        n = max(1, int(math.ceil(duration * rate - _EPS)))
        duration = float(n) / rate
        u = _sample_grid(n)

        if lin_dist >= _EPS:
            alpha_lin = _lspb_alpha_for_duration(lin_dist, speed_m_s, acc_m_s2, duration)
            s_lin = _lspb_displacement(u, lin_dist, alpha_lin) / lin_dist
        else:
            s_lin = u
        if rot_dist >= _EPS:
            alpha_rot = _lspb_alpha_for_duration(rot_dist, rot_speed_rad_s, rot_acc_rad_s2, duration)
            s_rot = _lspb_displacement(u, rot_dist, alpha_rot) / rot_dist
        else:
            s_rot = u

        # Mode 0 approximate-motion trigger mirrors firmware: once joint speed
        # would exceed joint_speed_limit_rad_s (C24), switch to 250 Hz native
        # [mm, rad] DLS for the remainder of the segment (or Chiaverini smooth
        # ramp if configured).
        mode0_approx_cfg = ApproxMotionConfig(
            damping=self._approx_config.damping,
            singular_value_threshold=self._approx_config.singular_value_threshold,
            trigger_joint_speed_rad_s=(
                self._approx_config.trigger_joint_speed_rad_s
                if self._approx_config.trigger_joint_speed_rad_s is not None
                else self._joint_speed_limit_rad_s
            ),
            max_position_error_m=self._approx_config.max_position_error_m,
            max_orientation_error_rad=self._approx_config.max_orientation_error_rad,
            position_unit_scale=self._approx_config.position_unit_scale,
        )

        q_rows: list[FloatArray] = []
        cur_q = q0.copy()
        approx_steps = 0
        max_pos_err = 0.0
        max_rot_err = 0.0
        max_vj = 0.0
        segment_in_approx = False
        err_code = ERROR_NONE
        err_msg = ""

        for k in range(n):
            pose_k: FloatArray = np.eye(4, dtype=np.float64)
            pose_k[:3, 3] = p0 + float(s_lin[k]) * (p1 - p0)
            pose_k[:3, :3] = slerp_rotation(r0, r1, float(s_rot[k]))
            try:
                step_res = solve_cartesian_step(
                    self._chain,
                    pose_k,
                    cur_q,
                    allow_approx_motion=self._allow_approx_motion,
                    approx_config=mode0_approx_cfg,
                    dt_s=dt,
                    include_tcp=include_tcp,
                    force_approx=segment_in_approx,
                )
            except ValueError as exc:
                err_code = ERROR_IK_FAILED
                err_msg = str(exc)
                break

            step_speed = float(np.max(np.abs(step_res.q_rad - cur_q))) / dt
            if not self._allow_approx_motion and step_speed > self._joint_speed_limit_rad_s:
                err_code = ERROR_OVERSPEED
                err_msg = (
                    f"joint speed {step_speed:.3f} rad/s exceeds limit {self._joint_speed_limit_rad_s:.3f} rad/s "
                    f"at MoveL tick {k} (C24 overspeed)"
                )
                break

            if step_res.used_approx:
                approx_steps += 1
                if mode0_approx_cfg.singular_value_threshold == 0.0:
                    segment_in_approx = True
            max_vj = max(max_vj, step_speed)
            max_pos_err = max(max_pos_err, step_res.position_error_m)
            max_rot_err = max(max_rot_err, step_res.orientation_error_rad)
            cur_q = step_res.q_rad
            q_rows.append(cur_q.copy())

        if err_code != ERROR_NONE and motion_type == 1:
            return self.plan_move_l(
                target,
                start_q_rad=q0,
                rate_hz=rate,
                motion_type=2,
                include_tcp=include_tcp,
            )

        samples = np.stack(q_rows, axis=0) if q_rows else q0.reshape(1, -1)
        ts = np.arange(1, len(samples) + 1, dtype=np.float64) / rate
        return PlannedMotion(
            kind="movel",
            rate_hz=rate,
            duration_s=float(len(samples)) / rate,
            q_samples=samples,
            timestamps_s=ts,
            error_code=err_code,
            used_approx_steps=approx_steps,
            max_position_error_m=max_pos_err,
            max_orientation_error_rad=max_rot_err,
            max_joint_speed_rad_s=max_vj,
            message=err_msg,
        )

    def set_position(
        self,
        x: float | None = None,
        y: float | None = None,
        z: float | None = None,
        roll: float | None = None,
        pitch: float | None = None,
        yaw: float | None = None,
        *,
        speed: float | None = None,
        mvacc: float | None = None,
        is_radian: bool = True,
        wait: bool = False,
        motion_type: int = 0,
    ) -> int:
        """Mode 0 Cartesian MoveL (mirrors ``XArmAPI.set_position``) at ``control_rate_hz`` (250 Hz default)."""

        if self._mode != MODE_POSITION or self._state != STATE_READY or self._error_code != ERROR_NONE:
            return ERROR_INVALID_MODE
        if motion_type not in (0, 1, 2):
            return ERROR_INVALID_ARG

        cur_pose = self._chain.forward_pose_mm_rpy(self._q_rad, include_tcp=True)
        vals = [
            cur_pose[0] if x is None else float(x),
            cur_pose[1] if y is None else float(y),
            cur_pose[2] if z is None else float(z),
            cur_pose[3] if roll is None else (float(roll) if is_radian else math.radians(float(roll))),
            cur_pose[4] if pitch is None else (float(pitch) if is_radian else math.radians(float(pitch))),
            cur_pose[5] if yaw is None else (float(yaw) if is_radian else math.radians(float(yaw))),
        ]
        if not all(math.isfinite(v) for v in vals):
            return ERROR_INVALID_ARG

        spd_mm_s = DEFAULT_MOVEL_SPEED_MM_S if speed is None else float(speed)
        acc_mm_s2 = DEFAULT_MOVEL_ACC_MM_S2 if mvacc is None else float(mvacc)
        if spd_mm_s <= 0.0 or acc_mm_s2 <= 0.0:
            return ERROR_INVALID_ARG

        target_se3 = pose_to_se3(vals, position_in_mm=True)
        motion = self.plan_move_l(
            target_se3,
            speed_m_s=spd_mm_s * 1e-3,
            acc_m_s2=acc_mm_s2 * 1e-3,
            motion_type=motion_type,
            include_tcp=True,
        )
        self._last_motion = motion
        if motion.error_code != ERROR_NONE:
            self._q_rad = motion.q_samples[-1].copy()
            self._error_code = motion.error_code
            self._state = STATE_STOP
            return motion.error_code

        if self._hardware_arm is not None:
            code = int(
                self._hardware_arm.set_position(
                    x=vals[0],
                    y=vals[1],
                    z=vals[2],
                    roll=vals[3],
                    pitch=vals[4],
                    yaw=vals[5],
                    speed=spd_mm_s,
                    mvacc=acc_mm_s2,
                    is_radian=True,
                    wait=wait,
                    motion_type=motion_type,
                )
            )
            if code != 0:
                return code

        self._q_rad = motion.q_samples[-1].copy()
        return ERROR_NONE

    # ------------------------------------------------------------------ Mode 1 servo streaming (30-250 Hz, default 50 Hz)

    def set_servo_angle_j(self, angles: Sequence[float] | FloatArray, *, is_radian: bool = True) -> int:
        """Mode 1 single-tick joint servo command (mirrors ``XArmAPI.set_servo_angle_j``)."""

        if self._mode != MODE_SERVO or self._state != STATE_READY or self._error_code != ERROR_NONE:
            return ERROR_INVALID_MODE
        raw = np.asarray(angles, dtype=np.float64).reshape(-1)
        if raw.shape != (self.dof,) or not np.all(np.isfinite(raw)):
            return ERROR_INVALID_ARG
        q_target = raw if is_radian else np.deg2rad(raw)
        if np.any(q_target < self._chain.lower - 1e-7) or np.any(q_target > self._chain.upper + 1e-7):
            self._error_code = ERROR_INVALID_ARG
            self._state = STATE_STOP
            return ERROR_INVALID_ARG
        if self._hardware_arm is not None:
            code = int(self._hardware_arm.set_servo_angle_j(angles=q_target.tolist(), is_radian=True))
            if code != 0:
                return code
        self._q_rad = q_target.copy()
        return ERROR_NONE

    def set_servo_cartesian(
        self,
        mvpose: Sequence[float] | FloatArray,
        *,
        is_radian: bool = True,
        dt_s: float | None = None,
    ) -> int:
        """Mode 1 single-tick Cartesian servo command (mirrors ``XArmAPI.set_servo_cartesian``)."""

        if self._mode != MODE_SERVO or self._state != STATE_READY or self._error_code != ERROR_NONE:
            return ERROR_INVALID_MODE
        raw = np.asarray(mvpose, dtype=np.float64).reshape(-1)
        if raw.shape != (6,) or not np.all(np.isfinite(raw)):
            return ERROR_INVALID_ARG
        pose_rad = raw.copy()
        if not is_radian:
            pose_rad[3:] = np.deg2rad(pose_rad[3:])
        target_se3 = pose_to_se3(pose_rad, position_in_mm=True)
        step_dt = (1.0 / self._servo_rate_hz) if dt_s is None else float(dt_s)
        try:
            res = solve_cartesian_step(
                self._chain,
                target_se3,
                self._q_rad,
                allow_approx_motion=self._allow_approx_motion,
                approx_config=self._approx_config,
                dt_s=step_dt,
                include_tcp=True,
            )
        except ValueError:
            self._error_code = ERROR_IK_FAILED
            self._state = STATE_STOP
            return ERROR_IK_FAILED
        self._last_step = res
        if self._hardware_arm is not None:
            code = int(self._hardware_arm.set_servo_cartesian(mvpose=pose_rad.tolist(), is_radian=True))
            if code != 0:
                return code
        self._q_rad = res.q_rad.copy()
        return ERROR_NONE

    # ------------------------------------------------------------------ Domain / SafetyGate protocol methods (metres, flange)

    def forward(self, q_rad: FloatArray) -> FloatArray:
        """``KinematicsBackend.forward``: base-frame flange pose ``[x, y, z, qx, qy, qz, qw]`` (m)."""

        return self._chain.forward_pose_m_quat(q_rad, include_tcp=False)

    def jacobian(self, q_rad: FloatArray) -> FloatArray:
        """``JacobianKinematicsBackend.jacobian``: 6xN spatial Jacobian ``[v_m; w_rad]`` at flange."""

        return self._chain.jacobian(q_rad, include_tcp=False)

    def solve_step(
        self,
        target_pose: FloatArray,
        seed_q_rad: FloatArray,
        *,
        dt_s: float | None = None,
        include_tcp: bool = False,
    ) -> IKStepResult:
        """Solve one flange/TCP Cartesian step (accepts ``xyz+rpy`` len 6 or ``xyz+quat_xyzw`` len 7 in m)."""

        target_se3 = pose_to_se3(target_pose, position_in_mm=False)
        step_dt = (1.0 / self._servo_rate_hz) if dt_s is None else float(dt_s)
        res = solve_cartesian_step(
            self._chain,
            target_se3,
            seed_q_rad,
            allow_approx_motion=self._allow_approx_motion,
            approx_config=self._approx_config,
            dt_s=step_dt,
            include_tcp=include_tcp,
        )
        self._last_step = res
        return res

    def inverse(self, pose: FloatArray, seed_q_rad: FloatArray) -> FloatArray:
        """``KinematicsBackend.inverse``: solve flange ``xyz+quat_xyzw`` (or ``xyz+rpy``) in metres."""

        return self.solve_step(pose, seed_q_rad, include_tcp=False).q_rad

    def solve_cartesian_segment(
        self,
        poses: FloatArray,
        seed_q_rad: FloatArray,
        *,
        rate_hz: float | None = None,
        include_tcp: bool = False,
    ) -> tuple[FloatArray, tuple[IKStepResult, ...]]:
        """Sequentially solve a stream of Cartesian poses (metres, len 6 or 7) preserving seed continuity."""

        arr = np.asarray(poses, dtype=np.float64)
        if arr.ndim != 2 or arr.shape[0] < 1 or arr.shape[1] not in (6, 7):
            raise ValueError(f"poses must have shape (N, 6) or (N, 7), got {arr.shape}")
        step_dt = 1.0 / (self._servo_rate_hz if rate_hz is None else float(rate_hz))
        cur_q = self._chain.validate_q(seed_q_rad).copy()
        q_rows: list[FloatArray] = []
        results: list[IKStepResult] = []
        for row in arr:
            res = self.solve_step(row, cur_q, dt_s=step_dt, include_tcp=include_tcp)
            cur_q = res.q_rad
            q_rows.append(cur_q.copy())
            results.append(res)
        return np.stack(q_rows, axis=0), tuple(results)

    # ------------------------------------------------------------------ Hardware switch sync context manager

    @contextmanager
    def sync_hardware_switches(self, arm: Any) -> Iterator[None]:
        """Apply controller ``allow_approx_motion`` to an ``XArmAPI`` instance and restore it unconditionally."""

        read_code, prev_approx = arm.get_allow_approx_motion()
        if int(read_code) != 0:
            raise RuntimeError(f"get_allow_approx_motion failed with SDK code {read_code}")
        set_code = int(arm.set_allow_approx_motion(self._allow_approx_motion))
        if set_code != 0:
            raise RuntimeError(f"set_allow_approx_motion({self._allow_approx_motion}) failed with SDK code {set_code}")
        try:
            yield
        finally:
            restore_code = int(arm.set_allow_approx_motion(bool(prev_approx)))
            if restore_code != 0:
                raise RuntimeError(
                    f"failed to restore controller allow_approx_motion={bool(prev_approx)} (SDK code={restore_code})"
                )
